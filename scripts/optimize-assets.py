"""Rebuild compact assets without removing geography or reducing particle counts."""
from pathlib import Path
from PIL import Image
import json, struct, hashlib
from shapely.geometry import shape, mapping

root=Path(__file__).resolve().parents[1]/'dist'
source=root/'assets'
output=source/'optimized'
output.mkdir(exist_ok=True)
manifest={'pointScale':30000}
report={}
def emit(key, data, ext, original_size):
    digest=hashlib.sha256(data).hexdigest()[:12]
    name=f'{key}.{digest}.{ext}'
    (output/name).write_bytes(data)
    manifest[key]=f'./assets/optimized/{name}'
    report[key]={'before':original_size,'after':len(data)}

import io
for key, filename, quality in [('day','earth-day.jpg',88),('clouds','earth-clouds.png',84),('night','earth-night.png',90),('moon','moon-texture.png',86)]:
    p=source/filename
    image=Image.open(p)
    if key=='clouds':image=image.resize((1024,512),Image.Resampling.LANCZOS)
    buffer=io.BytesIO()
    image.save(buffer,format='WEBP',quality=quality,method=6)
    emit(key,buffer.getvalue(),'webp',p.stat().st_size)

for key, filename in [('land','land-points-dense.json'),('ocean','ocean-points-dense.json'),('mapDots','land-points.json')]:
    p=source/filename
    values=json.loads(p.read_text(encoding='utf-8'))
    assert max(map(abs,values))<32767/manifest['pointScale']
    packed=struct.pack('<'+'h'*len(values),*(round(v*manifest['pointScale']) for v in values))
    emit(key,packed,'i16',p.stat().st_size)
    manifest[key+'Count']=len(values)//3

def compact_coordinates(value):
    if isinstance(value,(list,tuple)):return [compact_coordinates(v) for v in value]
    return round(value,4)
p=source/'world-countries.geojson'
geo=json.loads(p.read_text(encoding='utf-8'))
for feature in geo['features']:
    feature['properties']={k:v for k,v in feature['properties'].items() if k in ['NAME_ZH','NAME_EN','ADMIN','NAME']}
    # Subpixel at the map's maximum zoom; retain every component and hole.
    original=shape(feature['geometry'])
    compact=original.simplify(.012,preserve_topology=True)
    if not compact.is_empty and compact.geom_type==original.geom_type:
        feature['geometry']=mapping(compact)
    feature['geometry']['coordinates']=compact_coordinates(feature['geometry']['coordinates'])
emit('world',json.dumps(geo,ensure_ascii=False,separators=(',',':')).encode(),'json',p.stat().st_size)
(root/'atlas-assets.js').write_text('// Generated by scripts/optimize-assets.py. Hashes make long-term caching safe.\nexport const assets='+json.dumps(manifest,separators=(',',':'))+';\n',encoding='utf-8')
print(json.dumps(report,indent=2))
